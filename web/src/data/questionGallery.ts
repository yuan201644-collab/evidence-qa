/**
 * 问题灵感库（输入框左侧四角星按钮的数据源）。
 *
 * 评委第一次打开界面最大的问题不是「答案对不对」，而是「我不知道能问什么」。
 * 首页两张示例卡只放 5 句，覆盖不了系统的能力面。这份清单按**这套方法实际
 * 能做的事**分组，每组附一句「该看哪里」——把注意力引到事实表、证据块、条款
 * 引用上，让演示顺带完成核心机制的验证。
 *
 * 三条硬约束（改动前必读）：
 *
 * 1. **只放冻结题库（`qbank_v4.json`，31 题）里的原句，一字不改。**
 *    依据是「页面上的每句话都必须真的跑通过」。改一个字就变成未验证问句，
 *    演示时答错没法解释。
 * 2. **必须是自足的句子。** 题库里有一批题以「上述三份名单」「该名单」「该办法」
 *    开头，它们依赖上一题的上下文，单独贴进输入框时模型不知道指哪份文件。
 *    这类题一律不进灵感库（M-02/04/07/10/12… 里的指代题、B-02、B-05）。
 * 3. **每组第一条必须是「事实表覆盖完整 + v19b–v21 五轮跑批全对」的题。**
 *    这是被实测推翻过一次的教训：M-17 五轮判分都算对，但事实表只有「全类别
 *    合计」一行，题面却还问「分别属于哪些类别」——界面单发时模型表里找不到
 *    分类明细，回原文数错，答成「1 项」（正确是 10 项）。判分器查数值所以判对，
 *    人一看就错。所以**出表行数要 ≥2 且覆盖题面每一问**，才算安全牌。
 *
 * 另外每条都标了预计耗时：这套链路的单题中位数约 2 分钟、长尾可到 5 分钟，
 * 不提前说清楚，演示时会被当成卡死。
 *
 * 逐题的安全牌清单（出表行数 / 五轮判定）见 `reports/_demo_safe_questions.md`。
 */

export interface GalleryQuestion {
  question: string
  /** 可选：这句的说明，悬停可见 */
  note?: string
}

export interface GalleryGroup {
  id: string
  title: string
  /** 这组验证什么能力（对应架构里的哪一环） */
  purpose: string
  /** 演示时该看哪里 */
  watch: string
  icon: string
  questions: GalleryQuestion[]
}

